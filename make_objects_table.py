# ── Срезы и стиль через сам Excel (openpyxl их не умеет) ──────────────────────
def _rgb(hex_: str) -> int:
    r, g, b = int(hex_[0:2], 16), int(hex_[2:4], 16), int(hex_[4:6], 16)
    return r + g * 256 + b * 65536


def _slicer_style(wb):
    """Фирменный стиль кнопок: выбранные — синие, невыбранные — светлые, пустые — бледные."""
    name = 'Аквабарьер2'
    try:
        return wb.SlicerStyles(name).Name
    except Exception:
        pass
    try:
        st = wb.TableStyles.Add(name)
        st.ShowAsAvailableSlicerStyle = True
        st.ShowAsAvailableTableStyle = False
        st.ShowAsAvailablePivotTableStyle = False
        el = st.TableStyleElements
        whole = el(0)                                     # xlWholeTable
        whole.Font.Name = FONT
        whole.Font.Color = _rgb(INK)
        hdr = el(1)                                       # xlHeaderRow — заголовок среза
        hdr.Font.Bold = True
        hdr.Font.Color = _rgb(NAVY)
        for code, fill, color in ((28, 'FFFFFF', INK),     # невыбранные с данными
                                  (29, 'FFFFFF', 'C2C9D2'),  # без данных
                                  (30, 'D6E6FB', NAVY),      # выбранные
                                  (31, 'EEF2F7', 'A9B4C2'),  # выбранные, но пустые
                                  (32, 'EEF4FB', NAVY),      # наведение на невыбранную
                                  (33, 'B9D3F5', NAVY)):     # наведение на выбранную
            e = el(code)
            e.Interior.Color = _rgb(fill)
            e.Font.Color = _rgb(color)
        return name
    except Exception as e:
        print(f'  свой стиль кнопок не создался ({e}) — беру стандартный')
        return 'SlicerStyleLight1'


def add_slicers(path: Path, start: int):
    try:
        import win32com.client as win32
    except ImportError:
        print('pywin32 не установлен — срезы пропущены (фильтры в заголовках работают).')
        return
    xl = win32.DispatchEx('Excel.Application')
    xl.Visible = False
    xl.DisplayAlerts = False
    try:
        wb = xl.Workbooks.Open(str(path.resolve()))
        ws = wb.Worksheets('Объекты')
        lo = ws.ListObjects('Objects')
        style = _slicer_style(wb)
        top = ws.Range('A7').Top + 6                 # строка 6 занята текстом с правилами
        height = ws.Range(f'A{start}').Top - top - 8
        x = ws.Range('A7').Left + 8
        # поле, подпись, ширина, колонок кнопок, порядок (1 — как в таблице, 2 — по алфавиту), скрывать пустые
        # Пустые регионы/города не прячем, а ставим вниз бледными: ничего «не пропадает»
        # cross: 3 — бледные на своих местах, 2 — с данными наверху, 4 — прятать пустые
        specs = [('Тип объекта', 'Тип объекта   ·   все — ✕ справа', 430, 3, 3),
                 ('Подтип', 'Подтип / вместимость школ   ·   все — ✕', 330, 2, 4),
                 ('Регион', 'Регион   ·   все — ✕ справа', 470, 3, 2),
                 ('Город', 'Город   ·   все — ✕', 300, 2, 2)]
        for field, cap, w, ncol, cross in specs:
            sc = wb.SlicerCaches.Add2(lo, field)
            sc.SortItems = 2                         # по алфавиту; нужный порядок задан невидимыми символами
            sc.CrossFilterType = cross
            s = sc.Slicers.Add(ws, Name='S_' + re.sub(r'\W', '', field), Caption=cap)
            s.Caption = cap                         # при создании Excel подпись игнорирует
            s.Top, s.Left, s.Width, s.Height = top, x, w, height
            s.NumberOfColumns = ncol
            s.RowHeight = 19
            s.Style = style
            x += w + 8
        ws.Activate()
        xl.ActiveWindow.ScrollRow = 1
        ws.Range(f'A{start + 1}').Select()
        wb.Worksheets('Обзор').Activate()
        wb.Save()
        wb.Close(True)
        print('Срезы добавлены.')
    finally:
        xl.Quit()


