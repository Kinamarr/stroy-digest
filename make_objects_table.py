def enrich(d: dict) -> dict:
    name, addr, descr = d['Название объекта'], d.get('Адрес', ''), d.get('Описание / Новость', '')
    descr = descr if isinstance(descr, str) else ''
    # Регион
    region = canon_region(d.get('Регион', ''))
    tab = d.pop('_tab', '')
    if not region and tab and tab != 'Вся Россия':
        region = canon_region(tab)
    if not region:
        region = guess_region([addr, name, descr[:300]])
    d['Регион'] = region or NO_REGION
    d['Федеральный округ'] = REGION_FO.get(region, 'Вся РФ')
    # Город
    city = d.get('Город', '') if d.get('Город', '') not in ('', NO_CITY) else ''
    if not city:
        if region in CITY_OF_FED:
            city = region
        else:
            city = find_city([addr, name, descr[:300]], region)
            if not city and tab and CITY_INDEX.get(tab) == region:
                city = tab                      # вкладка-город старой книги («Воронеж»)
    d['Город'] = city or NO_CITY
    # Тип и подтип
    t = d.get('Тип объекта', '')
    if t not in TYPE_NAMES or t == 'Прочее':
        t = ''
    g, s = classify(name, descr)
    if not t:
        t = g
    sub = d.get('Подтип', '')
    if t == 'Школы':
        n = d.get('Мест') or capacity(f'{name} {addr} {descr}')
        try:
            n = int(n) if n else None
        except (TypeError, ValueError):
            n = capacity(str(n))
        d['Мест'] = n or ''
        sub = school_band(n)
    elif t == 'Детские сады':
        n = d.get('Мест') or capacity(f'{name} {descr}')
        d['Мест'] = n or ''
        sub = sub or 'Детский сад'
    elif not sub or sub not in SUBTYPE_ORDER.get(t, []):
        sub = s if g == t and s else (_first_sub(t, name, descr) or 'Другое')
    d['Тип объекта'], d['Подтип'] = t, sub
    return d


def _first_sub(t: str, name: str, descr: str) -> str:
    for text in (name, descr[:250]):
        for g, s, rx in _RULES_RE:
            if g == t and s and rx.search(text or ''):
                return s
    return ''


def _added_ordinal(v) -> int:
    """Дата добавления → число для сортировки (без даты — 0, т. е. в самый конец)."""
    if isinstance(v, datetime):
        return v.toordinal()
    m = re.match(r'(\d{4})-(\d{2})-(\d{2})', str(v or ''))
    if m:
        return datetime(*map(int, m.groups())).toordinal()
    m = re.match(r'(\d{2})\.(\d{2})\.(\d{4})', str(v or ''))
    return datetime(int(m.group(3)), int(m.group(2)), int(m.group(1))).toordinal() if m else 0


def sort_key(d: dict):
    # Свежедобавленные объекты — первыми; внутри одной даты — по типу, подтипу, региону
    t = d['Тип объекта']
    subs = SUBTYPE_ORDER.get(t, [])
    return (-_added_ordinal(d.get('Дата добавления')),
            TYPE_NAMES.index(t), subs.index(d['Подтип']) if d['Подтип'] in subs else 99,
            d['Регион'] == NO_REGION, d['Регион'], d['Город'] == NO_CITY, d['Город'], d['Название объекта'])


