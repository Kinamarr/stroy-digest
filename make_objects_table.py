# Вместимость школы: «на 1100 учеников», «1 500 мест»
CAP_RE = re.compile(r'(?<!\d)(\d{1,2}[\s ]?\d{3}|\d{3,4})\s*(?:-?ти\s*)?(?:учени|мест|учащ|школьник|обучающ)',
                    re.I)
SCHOOL_BANDS = [(500, 'до 500 мест'), (1000, '500–1000 мест'), (1500, '1000–1500 мест'),
                (2000, '1500–2000 мест'), (10 ** 6, '2000 мест и более')]
NO_CAP = 'вместимость не указана'
SUBTYPE_ORDER = {g: [] for g in TYPE_NAMES}
for _g, _s, _ in _RULES:
    if _s and _s not in SUBTYPE_ORDER[_g]:
        SUBTYPE_ORDER[_g].append(_s)
SUBTYPE_ORDER['Школы'] = [b for _, b in SCHOOL_BANDS] + [NO_CAP]


# Excel сортирует кнопки среза только по алфавиту. Невидимые символы нулевой ширины перед названием
# задают нужный порядок (чем их больше, тем выше кнопка): медучреждения первыми, «Прочее» — последним.
ZW = '​'


def ordered(label: str, rank: int, total: int = 40) -> str:
    return ZW * (total - rank) + label


def type_label(t: str) -> str:
    return ordered(t, TYPE_NAMES.index(t)) if t in TYPE_NAMES else t


def sub_label(t: str, sub: str) -> str:
    subs = SUBTYPE_ORDER.get(t, []) + ['Другое']
    if t not in TYPE_NAMES or sub not in subs:
        return sub
    return ordered(sub, TYPE_NAMES.index(t) * 12 + subs.index(sub), total=200)


def capacity(text: str):
    for m in CAP_RE.finditer(text or ''):
        n = int(re.sub(r'\D', '', m.group(1)))
        if 40 <= n <= 6000:
            return n
    return None


def school_band(n) -> str:
    if not n:
        return NO_CAP
    return next(b for lim, b in SCHOOL_BANDS if n < lim)


def classify(name: str, descr: str = '') -> tuple:
    for text in (name, (descr or '')[:250]):
        for g, s, rx in _RULES_RE:
            if text and rx.search(text):
                return g, s
    return 'Прочее', ''


