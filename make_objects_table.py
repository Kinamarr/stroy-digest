def canon_region(name: str, use_cities: bool = True) -> str:
    n = (name or '').strip()
    if not n:
        return ''
    if n in REGION_FO:
        return n
    low = re.sub(r'\s+', ' ', n.lower().replace(' обл.', ' область').replace('г. ', '')).strip()
    if low in REGION_ALIASES:
        return REGION_ALIASES[low]
    for r in REGION_FO:
        if r.lower() == low:
            return r
    if use_cities and n in CITY_INDEX:
        return CITY_INDEX[n]
    return ''


CITY_INDEX = {}
CITY_INDEX.update(_city_index())
# Длинные названия раньше коротких: «Нижний Новгород» раньше «Новгород»
_CITY_RE = [(c, re.compile(r'(?<![А-Яа-яЁё\-])' + re.escape(c[:-1]) + r'[а-яё]{0,3}(?![А-Яа-яЁё])'
                           if len(c) > 5 and c[-1] in 'аяоеьй' else
                           r'(?<![А-Яа-яЁё\-])' + re.escape(c) + r'[а-яё]{0,2}(?![А-Яа-яЁё])'))
            for c in sorted(CITY_INDEX, key=len, reverse=True)]
# «г. Дзержинск», но не «2026 г. Ввод в эксплуатацию» — после числа «г.» означает год
GORODE_RE = re.compile(r'(?<!\d)(?<!\d )\bг\.\s?([А-ЯЁ][а-яё]+(?:[\- ][А-ЯЁ][а-яё]+)?)')


def find_city(texts: list, region: str) -> str:
    """Город в адресе/названии. Принимаем только город того же региона (если регион известен)."""
    for t in texts:
        if not t:
            continue
        for c, rx in _CITY_RE:
            if rx.search(t) and (not region or CITY_INDEX[c] == region):
                return c
        m = GORODE_RE.search(t)
        if m and (not region or CITY_INDEX.get(m.group(1), region) == region):
            return m.group(1)
    return ''


def guess_region(texts: list) -> str:
    for t in texts:
        if not t:
            continue
        low = t.lower()
        for r in ALL_REGIONS:
            stem = r.split()[0][:-2].lower() if len(r.split()[0]) > 6 else r.lower()
            if stem and stem in low and r not in CITY_OF_FED:
                return r
        for c, rx in _CITY_RE:
            if rx.search(t):
                return CITY_INDEX[c]
    return ''


