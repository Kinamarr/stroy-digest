def _short_org(s: str) -> str:
    for a, b in (('ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ', 'ООО'), ('НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО', 'АО'),
                 ('ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО', 'ПАО'), ('АКЦИОНЕРНОЕ ОБЩЕСТВО', 'АО'),
                 ('ФЕДЕРАЛЬНОЕ КАЗЕННОЕ УЧРЕЖДЕНИЕ', 'ФКУ'), ('ГОСУДАРСТВЕННОЕ КАЗЕННОЕ УЧРЕЖДЕНИЕ', 'ГКУ'),
                 ('ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ', 'ГБУ'), ('МУНИЦИПАЛЬНОЕ КАЗЕННОЕ УЧРЕЖДЕНИЕ', 'МКУ')):
        s = re.sub(a, b, s, flags=re.I)
    return s


def _price(s: str) -> str:
    m = re.search(r'\d[\d\s\xa0]*', s or '')
    if not m:
        return ''
    return f"{int(re.sub(r'[^0-9]', '', m.group(0))):,}".replace(',', ' ') + ' руб.'


