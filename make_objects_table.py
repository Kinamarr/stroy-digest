EMAIL_RE = re.compile(r'[\w.\-+]+@[\w\-]+\.[\w.\-]+')
PHONE_RE = re.compile(r'^[\s+()\d\-–,;доб.]{7,}$')
SITE_RE = re.compile(r'^(https?://)?[\w\-]+(\.[\w\-]+)+(/\S*)?$', re.I)


def _s(v):
    if v is None:
        return ''
    if isinstance(v, datetime):
        return v
    return str(v).strip()


def parse_old_row(hdr: list, row: tuple) -> dict:
    """Строка вкладки региона старой книги → единый формат."""
    cells = dict(zip(hdr, row))
    d = {c: '' for c in COLUMNS}
    d['Тип объекта'] = OLD_TYPES.get(_s(cells.get('Тип объекта')), _s(cells.get('Тип объекта')))
    d['Название объекта'] = _s(cells.get('Название объекта'))
    d['Бюджет'] = _s(cells.get('Бюджет'))
    d['Адрес'] = _s(cells.get('Регион / Город / Адрес объекта'))
    d['Проектировщик'] = _s(cells.get('Проектировщик')).strip('?')
    d['Ген. подрядчик'] = _s(cells.get('Ген. Подрядчик') or cells.get('Ген. подрядчик')).strip('?')
    d['Заказчик'] = _s(cells.get('Заказчик'))
    d['Дата добавления'] = _s(cells.get('Дата добавления'))
    # Сайт / Email / Телефон / Описание на разных вкладках перепутаны — раскладываем по содержимому
    for col in ('Сайт', 'Email', 'Телефон', 'Описание / Новость'):
        v = _s(cells.get(col))
        if not v or isinstance(v, datetime):
            continue
        if len(v) > 60:
            target = 'Описание / Новость'
        elif EMAIL_RE.search(v):
            target = 'Email'
        elif PHONE_RE.match(v):
            target = 'Телефон'
        elif SITE_RE.match(v):
            target = 'Сайт'
        else:
            target = col if col != 'Сайт' else 'Описание / Новость'
        d[target] = (d[target] + '; ' + v) if d[target] else v
    return d


def read_rows(src: Path) -> list:
    wb = openpyxl.load_workbook(src)
    rows = []
    if 'Объекты' in wb.sheetnames:                         # новая книга
        ws = wb['Объекты']
        hdr_row = next(r for r in ws.iter_rows(min_row=1, max_row=40)
                       if [c.value for c in r][:2] == ['№', 'Тип объекта'])
        hdr = [c.value for c in hdr_row]
        for row in ws.iter_rows(min_row=hdr_row[0].row + 1, values_only=True):
            d = {c: (_s(v).replace(ZW, '') if isinstance(_s(v), str) else _s(v)) for c, v in zip(hdr, row) if c}
            if d.get('Название объекта'):
                d['Тип объекта'] = OLD_TYPES.get(d.get('Тип объекта', ''), d.get('Тип объекта', ''))
                rows.append(d)
        return rows
    for ws in wb.worksheets:                                 # старая книга: вкладки регионов
        if ws.title in ('Общее', 'Все объекты', 'Сводка'):
            continue
        hdr = [str(c).strip() if c else '' for c in next(ws.iter_rows(min_row=1, max_row=1, values_only=True))]
        for row in ws.iter_rows(min_row=2, values_only=True):
            if not row or len(row) < 2:
                continue
            d = parse_old_row(hdr, row)
            if d['Название объекта']:
                d['_tab'] = ws.title
                rows.append(d)
    return rows


