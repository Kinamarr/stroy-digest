# Названия регионов в таблице «Медиа РФ» → единое название
REGION_ALIASES = {
    'г. Москва': 'Москва',
    'г. Санкт-Петербург': 'Санкт-Петербург',
}


def normalize_region(name: str) -> str:
    """Регион из таблицы источников (на листе «Миллионники» там город) → субъект РФ."""
    name = (name or '').strip()
    name = REGION_ALIASES.get(name, name)
    return CITY_REGION.get(name, name)


def region_of(cities: list) -> str:
    """Первый найденный в тексте город → его регион."""
    for c in cities:
        if c in CITY_REGION:
            return CITY_REGION[c]
    return ''
